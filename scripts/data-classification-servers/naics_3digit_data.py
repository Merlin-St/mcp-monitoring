def format_naics_for_prompt() -> str:
    """Format NAICS codes as a string for LLM prompts"""
    lines = []
    for entry in NAICS_3DIGIT:
        lines.append(f"{entry['code']}: {entry['title']}")
        lines.append(f"   {entry['description']}")
        lines.append("")  # Blank line
    return "\n".join(lines)

def get_naics_title(code: str) -> str:
    """Get title for a NAICS code"""
    for entry in NAICS_3DIGIT:
        if entry["code"] == code:
            return entry["title"]
    return "Unknown"
